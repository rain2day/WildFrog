struct Mountain: Identifiable, Equatable {
    let id: String
    let nameZh: String
    let nameEn: String
    let region: String
    let height: Int
    let topRank: Int?
    let checkIns: Int
    let totalCheckIns: Int
    let imageName: String
    let coordinate: CLLocationCoordinate2D

    var displayName: String {
        nameEn.isEmpty ? nameZh : "\(nameZh) \(nameEn)"
    }

    var localizedName: String {
        if AppText.isEnglish {
            nameEn.isEmpty ? nameZh : nameEn
        } else {
            displayName
        }
    }

    var localizedPrimaryName: String {
        AppText.isEnglish && !nameEn.isEmpty ? nameEn : nameZh
    }

    var localizedSecondaryName: String {
        AppText.isEnglish ? nameZh : nameEn
    }

    var localizedRegion: String {
        AppText.region(region)
    }

    var rankText: String {
        MountainCatalog.heightRank(for: id).map { "#\($0)" } ?? "未排名"
    }

    var localizedRankText: String {
        MountainCatalog.heightRank(for: id).map { "#\($0)" } ?? AppText.value(zh: "未排名", en: "Unranked")
    }

    var stampImageName: String {
        MountainCatalog.stampImageName(for: id)
    }

    var usesIllustrativeImage: Bool {
        !MountainCatalog.documentaryImageIds.contains(id)
    }

    static func == (lhs: Mountain, rhs: Mountain) -> Bool {
        lhs.id == rhs.id
    }
}

enum MountainCatalog {
    static let catalogCount = 330

    /// Complete 1-based ranking by height (tallest = #1) covering every peak, so
    /// none shows "未排名". Ties broken by id for a stable order. ("300" stays the
    /// brand label; the rank value is real catalog data.)
    static let heightRankById: [String: Int] = {
        let sorted = mountains.sorted { lhs, rhs in
            lhs.height != rhs.height ? lhs.height > rhs.height : lhs.id < rhs.id
        }
        var map: [String: Int] = [:]
        for (index, mountain) in sorted.enumerated() {
            map[mountain.id] = index + 1
        }
        return map
    }()

    static func heightRank(for mountainId: String) -> Int? {
        heightRankById[mountainId]
    }

    static func heightRankSortValue(for mountainId: String) -> Int {
        heightRank(for: mountainId) ?? .max
    }

    static func stampImageName(for mountainId: String) -> String {
        let index = mountains.firstIndex { $0.id == mountainId } ?? 0
        return String(format: "WildFrogStamp%03d", index + 1)
    }

